// builds the offline file list (precache.js) and copies the site into www/ for capacitor.
// usage: node tools/build.js         (just the precache list)
//        node tools/build.js --www   (also copies everything into www/)
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const SKIP = new Set(['.git', 'node_modules', '_archive', 'www', 'android', 'ios', 'tools', '.github']);
const SKIP_FILES = new Set(['package.json', 'package-lock.json', 'capacitor.config.json', 'precache.js', 'Checklist.md', 'README.md', 'APP.md']);
const files = [];
(function walk(dir) {
    for (const name of fs.readdirSync(dir)) {
        if (name.startsWith('.')) continue;
        const full = path.join(dir, name);
        const rel = path.relative(root, full).split(path.sep).join('/');
        if (fs.statSync(full).isDirectory()) { if (!SKIP.has(name)) walk(full); continue; }
        if (SKIP_FILES.has(rel)) continue;
        files.push(rel);
    }
})(root);
files.sort();

const hash = crypto.createHash('sha1');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 10);
fs.writeFileSync(path.join(root, 'precache.js'),
    '// generated by tools/build.js, do not edit by hand\n' +
    'self.PRECACHE_VERSION = ' + JSON.stringify(version) + ';\n' +
    'self.PRECACHE = ' + JSON.stringify(['./', ...files.filter(f => f !== 'sw.js')], null, 0).replace(/","/g, '",\n"') + ';\n');
console.log('precache.js: ' + files.length + ' files, version ' + version);

if (process.argv.includes('--www')) {
    const out = path.join(root, 'www');
    fs.rmSync(out, { recursive: true, force: true });
    for (const f of [...files, 'precache.js']) {
        const dest = path.join(out, f);
        fs.mkdirSync(path.dirname(dest), { recursive: true });
        fs.copyFileSync(path.join(root, f), dest);
    }
    console.log('copied site into www/');
}
